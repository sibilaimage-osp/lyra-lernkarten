/* =====================================================
   THEMA ÖFFNEN
   ===================================================== */


function zeigeThema(thema) {

    const karte = lernkarten[thema];

    const bereich =
        document.getElementById("kartenBereich");


    if (!karte) {

        bereich.innerHTML = `

            <div class="karte fehlerKarte">

                <h2>⚠️ Thema nicht gefunden</h2>

                <p>
                    Für dieses Thema wurde noch keine Lernkarte angelegt.
                </p>

            </div>

        `;

        return;
    }


    bereich.innerHTML = `

        <div class="karte">

            <div class="kartenTop">

                <span class="kartenNummer">
                    🃏 LERNKARTE
                </span>

                <span class="kartenKapitel">
                    ${karte.kapitel}
                </span>

            </div>


            <h2>
                ${thema}
            </h2>


            <div class="frageBox">

                <span class="frageLabel">
                    FRAGE
                </span>

                <p class="frage">
                    ${karte.frage}
                </p>

            </div>


            <div class="antworten">

                ${karte.antworten.map(
                    function (antwort, index) {

                        return `

                            <button
                                class="antwort"
                                onclick="pruefeAntwort(
                                    ${index},
                                    '${thema.replace(/'/g, "\\'")}'
                                )"
                            >

                                <span class="buchstabe">
                                    ${String.fromCharCode(65 + index)}
                                </span>

                                <span>
                                    ${antwort}
                                </span>

                            </button>

                        `;

                    }
                ).join("")}

            </div>


            <div id="feedback"></div>


            <button
                class="zurueckButton"
                onclick="schliesseKarte()"
            >
                ← Zurück zu den Themen
            </button>

        </div>

    `;


    bereich.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}



/* =====================================================
   ANTWORT PRÜFEN
   ===================================================== */


function pruefeAntwort(index, thema) {

    const karte = lernkarten[thema];

    const antwortButtons =
        document.querySelectorAll(".antwort");

    const feedback =
        document.getElementById("feedback");


    if (!karte || !feedback) {
        return;
    }


    antwortButtons.forEach(
        function (button) {

            button.disabled = true;

        }
    );


    if (index === karte.richtig) {

        antwortButtons[index]
            .classList.add("richtig");


        feedback.innerHTML = `

            <div class="feedback richtigText">

                <div class="feedbackTitel">
                    ✅ Richtig!
                </div>

                <p>
                    ${karte.erklaerung}
                </p>

            </div>

        `;

    } else {

        antwortButtons[index]
            .classList.add("falsch");


        antwortButtons[karte.richtig]
            .classList.add("richtig");


        feedback.innerHTML = `

            <div class="feedback falschText">

                <div class="feedbackTitel">
                    ❌ Leider falsch.
                </div>

                <p>
                    Die richtige Antwort ist
                    <strong>
                        ${String.fromCharCode(
                            65 + karte.richtig
                        )}
                    </strong>.
                </p>

                <p>
                    ${karte.erklaerung}
                </p>

            </div>

        `;

    }

}



/* =====================================================
   KARTE SCHLIESSEN
   ===================================================== */


function schliesseKarte() {

    const bereich =
        document.getElementById("kartenBereich");


    bereich.innerHTML = `

        <div class="startHinweis">

            <div class="startIcon">
                🃏
            </div>

            <h2>
                Wähle ein Thema
            </h2>

            <p>
                Klicke oben auf ein Thema,
                um eine Lernkarte zu öffnen.
            </p>

        </div>

    `;

}
